// C# Program: Demonstrating Data Types

using System;

class Program
{
    static void Main()
    {
        // Integer type
        int age = 25;

        // Double type
        double height = 5.9;

        // Character type
        char grade = 'A';

        // String type
        string name = "Chandrakant";

        // Boolean type
        bool isStudent = true;

        // Display all variables
        Console.WriteLine("Name: " + name);
        Console.WriteLine("Age: " + age);
        Console.WriteLine("Height: " + height);
        Console.WriteLine("Grade: " + grade);
        Console.WriteLine("Is Student: " + isStudent);
    }
}


/* output: 
Name: Chandrakant
Age: 25
Height: 5.9
Grade: A
Is Student: True */
